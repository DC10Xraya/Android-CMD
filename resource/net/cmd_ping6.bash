cmd_ping6() {
    if [ "$1" = "-h" ] || [ "$1" = "--help" ] || [ $# -eq 0 ]; then
        ccat << "EOF"
//cecho -b "用法: PING6 [-n] [--inf] [-f|--ff|--fs] [-w] [-W] [-i] [-s] [-I] [-t] [-b] [-B] [-S] [-r] [-L] [-D] [-Dp] [-v] [-q] [-V] <域名/IP>"
//cecho -b "参数说明: "
-n 次数          指定发送的次数(正整数,默认4)
--inf            无限制发送(不限制包数)
-f               洪水模式(优先真实洪水, 失败则模拟)
--ff             强制使用系统洪水模式
--fs             强制使用模拟洪水模式
-w 总超时(s)     整个过程的总时间限制(正数)
-W 单包超时(s)   每个包的超时时间(正整数,默认1)
-i 间隔(s)       成功收到回复后等待的间隔时间(支持浮点数,>0,默认0.5)
                 root 设备可小于 0.2 秒; 非 root 最小 0.2 秒
-s 包大小(字节)  发送的数据包大小(1-65487, 默认56)
-I 接口/IP       指定源接口或源IP地址
-t HLIM          设置 IP 跳数限制 (1-255)
-b               允许 ping 广播地址
-B               不改变探测包的源地址
-S 缓冲区        设置发送缓冲区大小(字节)
-r               绕过路由表直接发送到本地接口
-L               抑制组播回环
-D               显示 Unix 时间戳
-Dp [格式]       显示人性化时间戳(格式可省略, 默认 HH:mm:ss)
//cecho -b "人性化格式(-fp)占位符:"
  YYYY=年  YY=两位年  MM=月  DD=日
  HH=24时  hh=12时  mm=分  ss=秒
  mmm=毫秒(3位总值)        如 802
  uuuuuu=微秒(6位总值)     如 802598
  uuu=微秒分量(3位)        如 598
  NNNNNNNNN=纳秒(9位总值)  如 802598399
  NN=纳秒分量(3位)         如 399
  AA=星期全称  aa=星期缩写
  TZ=时区偏移              如 +08:00
-v               直接显示系统的原始输出
-q               不显示每次回复, 只输出统计信息
-V               显示 PING 函数版本和底层 ping 版本
EOF
        return 0
    fi

    # ---- 过滤参数 ----
    local -a args=()
     local a
     for a in "$@"; do
        case "$a" in
            -4) err "未知参数: -4"; return 1 ;;
            -6) err "未知参数: -6"; return 1 ;;
            *)  args+=("$a") ;;
         esac
    done

    cmd_ping -6 "${args[@]}"
}